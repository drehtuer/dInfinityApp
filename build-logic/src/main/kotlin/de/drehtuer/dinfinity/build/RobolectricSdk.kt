package de.drehtuer.dinfinity.build

import com.android.build.api.dsl.CommonExtension
import org.gradle.api.Project
import org.gradle.api.tasks.TaskProvider
import org.gradle.kotlin.dsl.register

/**
 * Writes the one `robolectric.properties` every module's unit tests read.
 *
 * Robolectric takes the API to run against from a file on the test classpath,
 * and it has to be the same API in every module: one that forgot the file
 * silently ran against whatever Robolectric picked by default, and on this
 * project that is API 37 — which Robolectric cannot start at all. The failure
 * arrives as `NoSuchMethodException: InputManager.getInstance()` in a module
 * whose own code has nothing to do with input, which is a long way from "this
 * module has no properties file".
 *
 * So the file is generated rather than copied. A new module gets it by
 * applying the convention plugin, and raising the API is one line in
 * `gradle.properties` rather than six files to keep in step.
 */
internal fun Project.generateRobolectricProperties(android: CommonExtension) {
  val sdk = providers.gradleProperty(ROBOLECTRIC_SDK).get()
  val into = layout.buildDirectory.dir("generated/robolectric")

  val write: TaskProvider<*> =
    tasks.register("writeRobolectricProperties") {
      description = "Writes the robolectric.properties every unit test reads."
      group = "verification"
      inputs.property("sdk", sdk)
      outputs.dir(into)
      doLast {
        val file = into.get().file("robolectric.properties").asFile
        file.parentFile.mkdirs()
        file.writeText(
          """
          # Generated by the dinfinity convention plugins. Do not edit.
          #
          # Robolectric runs against this API rather than against targetSdk,
          # because it cannot start the one the app targets. The number lives
          # in gradle.properties as `$ROBOLECTRIC_SDK`.
          sdk=$sdk
          """.trimIndent() + "\n",
        )
      }
    }

  // Into the module's own test resources, which is where AGP's resource
  // processing will pick it up and where Robolectric looks for it. A plain
  // directory rather than a lazy one, because the Android source-set API
  // refuses a provider — so the ordering is wired by hand instead.
  android.sourceSets
    .getByName("test")
    .resources.directories += into.get().asFile.path
  tasks
    .matching { it.name.startsWith("process") && it.name.endsWith("UnitTestJavaRes") }
    .configureEach { dependsOn(write) }
}

private const val ROBOLECTRIC_SDK = "dinfinity.robolectricSdk"
